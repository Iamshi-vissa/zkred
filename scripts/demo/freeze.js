#!/usr/bin/env node
// npm run demo:freeze [-- --force]
//
// Copies the current production-circuit setup into the committed demo set
// (D27): web/public/circuit/{credential.wasm, credential.zkey, vkey.json,
// manifest.json} and contracts/demo/DemoCredentialVerifier.sol.
//
// Refuses to overwrite an existing frozen set without --force: re-freezing
// changes the verification key, so the Sepolia verifier must be redeployed.

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { MERKLE_DEPTH } from "../../zkred.config.js";
import { circuitPaths, ROOT } from "../circuits/compile.js";
import { setupPaths, isSetupCurrent, runSetup, releaseCurves } from "../circuits/setup.js";
import { PUBLIC_SIGNALS } from "../circuits/registry.js";
import { frozenPaths, sha256File, FROZEN_DIR, DEMO_VERIFIER_SOL, DEMO_VERIFIER_CONTRACT } from "./frozen.js";

export async function freeze({ dir = FROZEN_DIR, verifierSol = DEMO_VERIFIER_SOL, force = false, log = console.log } = {}) {
  const out = frozenPaths(dir);
  if (existsSync(out.manifest) && !force) {
    throw new Error(`a frozen demo setup already exists in ${path.relative(ROOT, dir)}; pass --force to replace it (then redeploy the verifier)`);
  }
  const depth = MERKLE_DEPTH;
  if (!isSetupCurrent(depth)) await runSetup({ depth, log });

  const c = circuitPaths(depth);
  const s = setupPaths(depth);
  const setup = JSON.parse(readFileSync(s.manifest, "utf8"));

  mkdirSync(dir, { recursive: true });
  copyFileSync(c.wasm, out.wasm);
  copyFileSync(s.zkey, out.zkey);
  copyFileSync(s.vkey, out.vkey);

  const sol = readFileSync(s.verifierSol, "utf8")
    .replace(/^\/\/ GENERATED.*\n\/\/ Do not edit.*\n/, "")
    .replace("contract CredentialVerifier", `contract ${DEMO_VERIFIER_CONTRACT}`);
  mkdirSync(path.dirname(verifierSol), { recursive: true });
  writeFileSync(
    verifierSol,
    `// FROZEN DEMO VERIFIER (D27). Generated by scripts/demo/freeze.js from\n` +
      `// web/public/circuit/credential.zkey; committed on purpose so the Sepolia\n` +
      `// deployment matches the key the browser proves with. Do not edit by hand.\n` +
      sol,
  );

  const manifest = {
    note: "Frozen demo setup for the live Sepolia demo (docs/decisions.md D27). One local contribution + beacon: trust the person who ran it. Not for production.",
    circuit: "circuits/credential.circom",
    depth,
    nConstraints: setup.nConstraints,
    publicSignals: PUBLIC_SIGNALS,
    r1csSha256: setup.r1csSha256,
    ptau: setup.ptau,
    ptauSha256: setup.ptauSha256,
    beacon: setup.beacon,
    files: Object.fromEntries(["wasm", "zkey", "vkey"].map((k) => [k, { file: path.basename(out[k]), sha256: sha256File(out[k]) }])),
    verifier: { contract: DEMO_VERIFIER_CONTRACT, path: path.relative(ROOT, verifierSol) },
    verifierSha256: sha256File(verifierSol),
    frozenAt: new Date().toISOString(),
  };
  writeFileSync(out.manifest, JSON.stringify(manifest, null, 2) + "\n");
  log(`frozen demo setup written to ${path.relative(ROOT, dir)} and ${path.relative(ROOT, verifierSol)}`);
  return manifest;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    await freeze({ force: process.argv.includes("--force") });
  } catch (e) {
    console.error(e.message);
    process.exitCode = 1;
  } finally {
    await releaseCurves();
  }
}
