#!/usr/bin/env node
// Generates build/circuits/<name>.circom (the `main` wrapper for a circuit at
// the configured MERKLE_DEPTH) and compiles it with circom.
//
//   npm run circuits:compile                      # every circuit, depth 10
//   npm run circuits:compile -- credential        # one circuit
//   ZKRED_MERKLE_DEPTH=16 npm run circuits:compile

import { mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import { MERKLE_DEPTH } from "../../zkred.config.js";
import { CIRCUITS, PUBLIC_SIGNALS, circuitSpec } from "./registry.js";

export { PUBLIC_SIGNALS };
export const ROOT = fileURLToPath(new URL("../..", import.meta.url));
export const CIRCUITS_OUT = path.join(ROOT, "build", "circuits");

/** Paths of the build outputs for a circuit at a given depth. */
export function circuitPaths(depth = MERKLE_DEPTH, id = "credential") {
  circuitSpec(id);
  const name = id === "credential" ? `credential_d${depth}` : `${id}_d${depth}`;
  return {
    name,
    main: path.join(CIRCUITS_OUT, `${name}.circom`),
    r1cs: path.join(CIRCUITS_OUT, `${name}.r1cs`),
    wasm: path.join(CIRCUITS_OUT, `${name}_js`, `${name}.wasm`),
    sym: path.join(CIRCUITS_OUT, `${name}.sym`),
  };
}

export function writeMain(depth = MERKLE_DEPTH, id = "credential") {
  const spec = circuitSpec(id);
  mkdirSync(CIRCUITS_OUT, { recursive: true });
  const { main } = circuitPaths(depth, id);
  writeFileSync(
    main,
    `pragma circom 2.1.6;\n// GENERATED by scripts/circuits/compile.js - do not edit.\n` +
      `include "../../${spec.source}";\n\n` +
      `component main {public [${PUBLIC_SIGNALS.join(", ")}]} = ${spec.template}(${depth});\n`,
  );
  return main;
}

export function compileCircuit(depth = MERKLE_DEPTH, { quiet = false, id = "credential" } = {}) {
  const spec = circuitSpec(id);
  const file = writeMain(depth, id);
  execFileSync(
    "circom",
    [file, `--${spec.optimization}`, "--r1cs", "--wasm", "--sym", "-l", path.join(ROOT, "node_modules"), "-o", CIRCUITS_OUT],
    { stdio: quiet ? "ignore" : "inherit" },
  );
  return circuitPaths(depth, id);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const ids = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(CIRCUITS);
  for (const id of ids) compileCircuit(MERKLE_DEPTH, { id });
}
