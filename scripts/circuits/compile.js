#!/usr/bin/env node
// Generates build/circuits/credential_d<DEPTH>.circom (the `main` wrapper for
// the configured MERKLE_DEPTH), compiles it with circom --O2.
//
//   npm run circuits:compile                      # depth 10
//   ZKRED_MERKLE_DEPTH=16 npm run circuits:compile

import { mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import { MERKLE_DEPTH } from "../../zkred.config.js";

export const PUBLIC_SIGNALS = ["root", "nullifierHash", "scope", "credentialType", "currentDate", "recipient"];

export const ROOT = fileURLToPath(new URL("../..", import.meta.url));
export const CIRCUITS_OUT = path.join(ROOT, "build", "circuits");

/** Paths of the build outputs for a given depth. */
export function circuitPaths(depth = MERKLE_DEPTH) {
  const name = `credential_d${depth}`;
  return {
    name,
    main: path.join(CIRCUITS_OUT, `${name}.circom`),
    r1cs: path.join(CIRCUITS_OUT, `${name}.r1cs`),
    wasm: path.join(CIRCUITS_OUT, `${name}_js`, `${name}.wasm`),
    sym: path.join(CIRCUITS_OUT, `${name}.sym`),
  };
}

export function writeMain(depth = MERKLE_DEPTH) {
  mkdirSync(CIRCUITS_OUT, { recursive: true });
  const { main } = circuitPaths(depth);
  writeFileSync(
    main,
    `pragma circom 2.1.6;\n// GENERATED by scripts/circuits/compile.js - do not edit.\n` +
      `include "../../circuits/credential.circom";\n\n` +
      `component main {public [${PUBLIC_SIGNALS.join(", ")}]} = Credential(${depth});\n`,
  );
  return main;
}

export function compileCircuit(depth = MERKLE_DEPTH, { quiet = false } = {}) {
  const file = writeMain(depth);
  execFileSync(
    "circom",
    [file, "--O2", "--r1cs", "--wasm", "--sym", "-l", path.join(ROOT, "node_modules"), "-o", CIRCUITS_OUT],
    { stdio: quiet ? "ignore" : "inherit" },
  );
  return circuitPaths(depth);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) compileCircuit();
